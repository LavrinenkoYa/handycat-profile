async function saveHM(){
  var name=document.getElementById("hmName").value.trim();
  if(!name){toast(t("toast_enter_name"));return;}
  var btn=document.getElementById("saveHMBtn");setLoading(btn,true);
  var eid=document.getElementById("editHMId").value;
  var sk=document.getElementById("hmSkills").value.split(",").map(function(s){return s.trim();}).filter(Boolean);
  var r=await api("save-handyman",{
    id:eid||undefined,name:name,
    phone:document.getElementById("hmPhone").value,email:document.getElementById("hmEmail").value,
    experience_years:document.getElementById("hmExp").value,skills:sk,card:document.getElementById("hmCard").value
  });
  setLoading(btn,false);
  if(!r.ok){
    if(r.error==="session_invalid"){clearSession();show("s-auth");return;}
    toast(r.error==="card_unavailable"?t("toast_card_unavailable"):t("toast_hm_save_error"));
    return;
  }
  var hm=rowToCamel(r.handyman);
  if(r.card){var ci=S.cards.findIndex(function(c){return c.id===r.card.id;});if(ci>=0)S.cards[ci]=rowToCamel(r.card);}
  var i=S.handymen.findIndex(function(h){return h.id===hm.id;});
  if(i>=0)S.handymen[i]=hm;else S.handymen.push(hm);
  closeModal("mHM");toast(eid?t("toast_hm_updated"):t("toast_hm_added"));
  renderHM();
  // Editing from the handyman card: refresh the card too, otherwise it keeps showing the old data.
  if(document.getElementById("cp-hm-detail").classList.contains("active"))showHMDetail(hm.id);
}

function delHM(id){
  if(!confirm(t("confirm_delete_hm")))return;
  (async function(){
    var r=await api("delete-handyman",{id:id});
    if(!r.ok){
      if(r.error==="session_invalid"){clearSession();show("s-auth");return;}
      toast(t("toast_request_error"));return;
    }
    S.handymen=S.handymen.filter(function(h){return h.id!==id;});
    // His card went back to the free pool on the server; show it as free here too.
    (r.released_cards||[]).forEach(function(cid){var c=S.cards.find(function(x){return x.id===cid;});if(c){c.status="unassigned";c.handymanId="";}});
    renderHM();toast(t("toast_hm_deleted"));
  })();
}

