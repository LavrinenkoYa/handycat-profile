async function init(){
  // Old, forgeable client-side "session" keys: remove them, they no longer mean anything.
  ["hc_company_id","hc_company_email","hc_company_session"].forEach(function(k){localStorage.removeItem(k);});
  var params=new URLSearchParams(window.location.search);
  var token=params.get("token");

  if(token){
    show("s-loading");
    var r=await api("exchange-link",{token:token});
    if(r.error!=="network")window.history.replaceState({},"","/company"); // never keep a login token in the address bar
    if(!r.ok){
      var map={
        link_invalid:["err_link_invalid_title","err_link_invalid_msg"],
        link_used:["err_link_used_title","err_link_used_msg"],
        link_expired:["err_link_expired_title","err_link_expired_msg"],
        account_not_found:["err_account_not_found_title","err_account_not_found_msg"],
        account_inactive:["err_account_inactive_title","err_account_inactive_msg"]
      };
      var m=map[r.error]||["err_generic_title","err_generic_msg"];
      showError(t(m[0]),t(m[1]));return;
    }
    setSession(r.session,r.session_expires_at);
    var ok=await bootstrapSession();
    if(ok===true)return;
    showError(t("err_generic_title"),t("err_generic_msg"));return;
  }

  if(getSession()){
    show("s-loading");
    var ok2=await bootstrapSession();
    if(ok2===true)return;
    if(ok2==="invalid"){clearSession();show("s-auth");return;}
    showError(t("err_generic_title"),t("err_generic_msg"));return; // e.g. offline: keep the session
  }
  show("s-auth");
}

